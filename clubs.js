const ClubsLR = (function () {
  const norm = s => String(s || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]/g, '');
  const parNom = {};
  Object.keys(CLUBS_OFFICIELS).forEach(n => { parNom[norm(CLUBS_OFFICIELS[n])] = n; });
  return {
    nom(num) { return CLUBS_OFFICIELS[String(num || '').replace(/\D/g, '')] || ''; },
    num(nom) { return parNom[norm(nom)] || ''; },
    estOfficiel(nom) { return !!parNom[norm(nom)]; },
    noms() { return Object.keys(CLUBS_OFFICIELS).map(n => CLUBS_OFFICIELS[n]).sort((a, b) => a.localeCompare(b, 'fr')); },
    total: Object.keys(CLUBS_OFFICIELS).length
  };
})();
